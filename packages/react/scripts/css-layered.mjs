#!/usr/bin/env node
// Opt-in layered CSS build (8.10). src/styles-layered/ is a generated copy of src/styles.css + src/styles/*.css where every
// rule sits in a cascade layer, so a host's Tailwind utilities override the SDK and the SDK's resets stop leaking:
//   @layer theme, base, aui, components, utilities;          (Tailwind v4's layers with `aui` between base and components)
//   @layer aui.reset, aui.tokens, aui.core, aui.chunk, aui.state;
//   aui.reset  = base element rules of tokens.css (box-sizing, margins, focus outline, links …)
//   aui.tokens = the `.adminui` root blocks (custom properties) and @keyframes of tokens.css
//   aui.core   = core.css;  aui.chunk = every area chunk;
//   aui.state  = reduced-motion / forced-colors / prefers-contrast blocks and `[data-aui-motion=none]` rules of any file
// Hosts opt in with Vite `resolve.conditions: ["aui-layered"]` (package.json "imports": "#aui-css/*" → styles-layered).
// The default build stays unlayered.
//   node scripts/css-layered.mjs          → check: the layered copies are up to date (exit 1 when stale / missing / extra)
//   node scripts/css-layered.mjs --write  → regenerate src/styles-layered/
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const stylesDir = join(root, "src", "styles");
export const LAYERED_DIR = join(root, "src", "styles-layered");
export const LAYER_ORDER = "@layer theme, base, aui, components, utilities;";
export const AUI_LAYERS = "@layer aui.reset, aui.tokens, aui.core, aui.chunk, aui.state;";
const lf = (text) => text.replace(/\r\n/g, "\n");

/** Top-level statements of a stylesheet (comments kept with the statement that follows them). */
export function topLevel(css) {
  const out = [];
  let depth = 0, from = 0, i = 0;
  while (i < css.length) {
    const c = css[i];
    if (c === "/" && css[i + 1] === "*") { const end = css.indexOf("*/", i + 2); i = end < 0 ? css.length : end + 2; continue; }
    if (c === '"' || c === "'") { let j = i + 1; while (j < css.length && css[j] !== c) j += css[j] === "\\" ? 2 : 1; i = j + 1; continue; }
    if (c === "{") depth++;
    else if (c === "}" && --depth === 0) { out.push(css.slice(from, i + 1).trim()); from = i + 1; }
    else if (c === ";" && depth === 0) { out.push(css.slice(from, i + 1).trim()); from = i + 1; }
    i++;
  }
  const rest = css.slice(from).trim();
  if (rest) out.push(rest);
  return out.filter(Boolean);
}
const prelude = (statement) => statement.replace(/\/\*[\s\S]*?\*\//g, "").split("{")[0].trim();
const STATE_MEDIA = /prefers-reduced-motion:\s*reduce|forced-colors|prefers-contrast/;
const isState = (p) => (p.startsWith("@media") && STATE_MEDIA.test(p)) || /\[data-aui-motion=("|')?none\1\]/.test(p);
const isRoot = (selector) => selector.split(",").every((s) => /^\.adminui(\[[^\]]+\])*$/.test(s.trim()));

/** Layer of one top-level statement of `chunk` (file name without .css). */
export function layerOf(chunk, statement) {
  const p = prelude(statement);
  if (isState(p)) return "state";
  if (chunk === "core") return "core";
  if (chunk !== "tokens") return "chunk";
  if (p.startsWith("@keyframes")) return "tokens";
  if (p.startsWith("@media")) {
    const inner = statement.slice(statement.indexOf("{") + 1, statement.lastIndexOf("}"));
    return topLevel(inner).every((s) => isRoot(prelude(s))) ? "tokens" : "reset";
  }
  return isRoot(p) ? "tokens" : "reset";
}

const header = (source) => `/* generated by scripts/css-layered.mjs from ${source} — do not edit; opt in with the "aui-layered" condition */\n${LAYER_ORDER}\n${AUI_LAYERS}\n`;

function layerChunk(chunk, css) {
  const groups = new Map();
  for (const statement of topLevel(lf(css))) {
    const layer = layerOf(chunk, statement);
    groups.set(layer, [...(groups.get(layer) ?? []), statement]);
  }
  let out = header(`src/styles/${chunk}.css`);
  for (const layer of ["reset", "tokens", "core", "chunk", "state"]) {
    const items = groups.get(layer);
    if (items) out += `@layer aui.${layer} {\n${items.join("\n")}\n}\n`;
  }
  return out;
}

/** file name in src/styles-layered → expected content. */
export function layeredFiles() {
  const files = new Map();
  for (const name of readdirSync(stylesDir).filter((n) => n.endsWith(".css")).sort()) {
    files.set(name, layerChunk(name.slice(0, -4), readFileSync(join(stylesDir, name), "utf8")));
  }
  // the core entry ("#aui-css/core.css" → styles.css): the same two imports as src/styles.css, layered copies
  const entry = lf(readFileSync(join(root, "src", "styles.css"), "utf8"));
  const imports = [...entry.matchAll(/@import\s+"\.\/styles\/([\w-]+\.css)";/g)].map((m) => `@import "./${m[1]}";`);
  files.set("styles.css", `${header("src/styles.css")}${imports.join("\n")}\n`);
  return files;
}

/** Problems that make the committed copies stale ([] = up to date). */
export function layeredProblems() {
  const want = layeredFiles();
  const have = existsSync(LAYERED_DIR) ? readdirSync(LAYERED_DIR).filter((n) => n.endsWith(".css")) : [];
  const problems = [];
  for (const [name, text] of want) {
    const path = join(LAYERED_DIR, name);
    if (!existsSync(path)) problems.push(`src/styles-layered/${name} is missing`);
    else if (lf(readFileSync(path, "utf8")) !== text) problems.push(`src/styles-layered/${name} is stale`);
  }
  for (const name of have) if (!want.has(name)) problems.push(`src/styles-layered/${name} has no source (removed chunk?)`);
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--write")) {
    rmSync(LAYERED_DIR, { recursive: true, force: true });
    mkdirSync(LAYERED_DIR, { recursive: true });
    for (const [name, text] of layeredFiles()) writeFileSync(join(LAYERED_DIR, name), text);
    console.log(`css-layered: wrote ${layeredFiles().size} files to src/styles-layered/`);
  } else {
    const problems = layeredProblems();
    if (problems.length) {
      console.error(`css-layered: ${problems.length} problem(s)\n- ${problems.join("\n- ")}\nFix: node scripts/css-layered.mjs --write`);
      process.exit(1);
    }
    console.log("css-layered ok: src/styles-layered/ matches src/styles/");
  }
}
